"""Firewall kill-switch adapter for Windows and Linux.

Provides reversible firewall rule insertion to prevent unencrypted public IP leaks
in the event of an unexpected VPN or proxy drop.
"""

from __future__ import annotations

import ctypes
import logging
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import List, Optional, Tuple

logger = logging.getLogger(__name__)

RULE_PREFIX = "IPChanger_KS"
IP_PATTERN = re.compile(r"^[0-9a-fA-F\.\:\/]+$")


class FirewallAdapter:
    """Manages system firewall rules to enact a fail-safe network kill switch."""

    def __init__(self) -> None:
        """Initialize FirewallAdapter with platform detection."""
        self._is_windows = sys.platform == "win32"
        self._is_linux = sys.platform.startswith("linux")
        self._is_active: bool = False
        self._backup_state: Optional[str] = None

    @staticmethod
    def requires_admin() -> bool:
        """Check if current process has required elevation to modify firewall rules."""
        if sys.platform == "win32":
            try:
                return bool(ctypes.windll.shell32.IsUserAnAdmin())  # type: ignore[attr-defined]
            except Exception:
                return False
        elif sys.platform.startswith("linux"):
            try:
                return os.geteuid() == 0  # type: ignore[attr-defined]
            except AttributeError:
                return False
        return False

    def is_active(self) -> bool:
        """Return whether the kill-switch rules are currently engaged."""
        return self._is_active

    def backup_rules(self) -> str:
        """Save a snapshot of existing firewall rules for emergency restoration.

        Returns:
            String representing backup file path or serialized rule configuration.
        """
        if not self.requires_admin():
            logger.warning("Cannot backup firewall rules without administrative privileges.")
            return ""

        if self._is_windows:
            backup_dir = Path(tempfile.gettempdir()) / "ip_changer"
            backup_dir.mkdir(parents=True, exist_ok=True)
            wfw_path = backup_dir / "firewall_backup.wfw"
            cmd = ["netsh", "advfirewall", "export", str(wfw_path)]
            try:
                res = subprocess.run(cmd, capture_output=True, text=True, timeout=10, check=False)
                if res.returncode == 0:
                    self._backup_state = str(wfw_path)
                    logger.info("Firewall backup successfully saved to %s", wfw_path)
                    return str(wfw_path)
                logger.error("Failed to export Windows firewall: %s", res.stderr)
            except Exception as exc:
                logger.error("Exception during Windows firewall export: %s", exc)

        elif self._is_linux:
            try:
                res = subprocess.run(
                    ["iptables-save"],
                    capture_output=True,
                    text=True,
                    timeout=5,
                    check=False,
                )
                if res.returncode == 0:
                    self._backup_state = res.stdout
                    return res.stdout
                logger.error("iptables-save failed: %s", res.stderr)
            except Exception as exc:
                logger.error("Exception running iptables-save: %s", exc)

        return ""

    def restore_rules(self, backup: str) -> bool:
        """Revert system firewall to the state recorded in the backup.

        Args:
            backup: File path (Windows) or rules dump (Linux) generated by backup_rules.

        Returns:
            True if restoration succeeded.
        """
        if not self.requires_admin():
            logger.error("Elevation required to restore firewall rules.")
            return False

        if not backup:
            return False

        if self._is_windows:
            wfw_path = Path(backup)
            if not wfw_path.exists():
                logger.error("Windows firewall backup file not found: %s", backup)
                return False
            cmd = ["netsh", "advfirewall", "import", str(wfw_path)]
            try:
                res = subprocess.run(cmd, capture_output=True, text=True, timeout=15, check=False)
                if res.returncode == 0:
                    self._is_active = False
                    logger.info("Restored Windows firewall from %s", backup)
                    return True
                logger.error("Failed to import Windows firewall: %s", res.stderr)
            except Exception as exc:
                logger.error("Error importing Windows firewall: %s", exc)

        elif self._is_linux:
            try:
                proc = subprocess.Popen(
                    ["iptables-restore"],
                    stdin=subprocess.PIPE,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                )
                _, err = proc.communicate(input=backup, timeout=10)
                if proc.returncode == 0:
                    self._is_active = False
                    logger.info("Restored Linux iptables rules from backup dump.")
                    return True
                logger.error("iptables-restore failed: %s", err)
            except Exception as exc:
                logger.error("Error executing iptables-restore: %s", exc)

        return False

    def enable_kill_switch(
        self,
        allowed_ips: Optional[List[str]] = None,
        vpn_interface: Optional[str] = None,
    ) -> Tuple[bool, str]:
        """Activate the kill-switch rules to enforce leak protection.

        Blocks non-VPN outbound traffic while allowing communication to the VPN server,
        local DNS, loopback, and local network.

        Args:
            allowed_ips: Explicit IP addresses (e.g. proxy or VPN endpoints) exempt from blocking.
            vpn_interface: Network interface name of the VPN tunnel (e.g., tun0, wg0).

        Returns:
            Tuple of (success: bool, status_message: str).
        """
        if not self.requires_admin():
            msg = (
                "Elevation required: Activating the network kill switch requires Administrator "
                "(Windows) or root (Linux) privileges. Please relaunch the application as Administrator."
            )
            logger.warning(msg)
            return False, msg

        # Take backup prior to modifying rules if not already taken
        if not self._backup_state:
            self.backup_rules()

        # Clean list of allowed IPs
        safe_allowed_ips = [
            ip.strip() for ip in (allowed_ips or [])
            if ip.strip() and IP_PATTERN.match(ip.strip())
        ]

        if self._is_windows:
            try:
                # 1. Clean up any existing IPChanger rules first
                self.disable_kill_switch()

                # 2. Allow Loopback and Local Subnet
                subprocess.run([
                    "netsh", "advfirewall", "firewall", "add", "rule",
                    f"name={RULE_PREFIX}_AllowLocal", "dir=out", "action=allow",
                    "remoteip=127.0.0.1,localsubnet"
                ], capture_output=True, check=True)

                # 3. Allow DNS for tunnel initialization
                subprocess.run([
                    "netsh", "advfirewall", "firewall", "add", "rule",
                    f"name={RULE_PREFIX}_AllowDNS", "dir=out", "action=allow",
                    "protocol=UDP", "remoteport=53"
                ], capture_output=True, check=True)

                # 4. Allow designated VPN/Proxy server endpoints
                if safe_allowed_ips:
                    remote_ip_arg = ",".join(safe_allowed_ips)
                    subprocess.run([
                        "netsh", "advfirewall", "firewall", "add", "rule",
                        f"name={RULE_PREFIX}_AllowVPNServers", "dir=out", "action=allow",
                        f"remoteip={remote_ip_arg}"
                    ], capture_output=True, check=True)

                # 5. Allow VPN tunnel interface traffic if specified
                if vpn_interface:
                    subprocess.run([
                        "netsh", "advfirewall", "firewall", "add", "rule",
                        f"name={RULE_PREFIX}_AllowTunnel", "dir=out", "action=allow",
                        f"interface={vpn_interface.strip()}"
                    ], capture_output=True, check=False)

                # 6. Block all other outbound traffic
                subprocess.run([
                    "netsh", "advfirewall", "firewall", "add", "rule",
                    f"name={RULE_PREFIX}_BlockOutbound", "dir=out", "action=block"
                ], capture_output=True, check=True)

                self._is_active = True
                msg = "Windows Firewall kill-switch rules successfully applied."
                logger.info(msg)
                return True, msg
            except subprocess.CalledProcessError as err:
                err_text = f"Failed to configure Windows Firewall rules: {err}"
                logger.error(err_text)
                self.disable_kill_switch()
                return False, err_text

        elif self._is_linux:
            try:
                # Remove prior chain if exists
                self.disable_kill_switch()

                # Create dedicated chain
                subprocess.run(["iptables", "-N", "IPCHANGER_KS"], capture_output=True, check=True)

                # Loopback
                subprocess.run(["iptables", "-A", "IPCHANGER_KS", "-o", "lo", "-j", "ACCEPT"], check=True)

                # Established connections
                subprocess.run([
                    "iptables", "-A", "IPCHANGER_KS", "-m", "conntrack",
                    "--ctstate", "ESTABLISHED,RELATED", "-j", "ACCEPT"
                ], check=True)

                # Tunnel interface
                if vpn_interface:
                    subprocess.run([
                        "iptables", "-A", "IPCHANGER_KS", "-o", vpn_interface.strip(), "-j", "ACCEPT"
                    ], check=True)

                # Allowed VPN / proxy endpoints
                for ip in safe_allowed_ips:
                    subprocess.run([
                        "iptables", "-A", "IPCHANGER_KS", "-d", ip, "-j", "ACCEPT"
                    ], check=True)

                # Allow DNS (UDP 53)
                subprocess.run([
                    "iptables", "-A", "IPCHANGER_KS", "-p", "udp", "--dport", "53", "-j", "ACCEPT"
                ], check=True)

                # Default DROP on custom chain
                subprocess.run(["iptables", "-A", "IPCHANGER_KS", "-j", "DROP"], check=True)

                # Insert into OUTPUT chain
                subprocess.run(["iptables", "-I", "OUTPUT", "1", "-j", "IPCHANGER_KS"], check=True)

                self._is_active = True
                msg = "Linux iptables kill-switch rules successfully applied."
                logger.info(msg)
                return True, msg
            except Exception as err:
                err_text = f"Failed to configure Linux iptables kill switch: {err}"
                logger.error(err_text)
                self.disable_kill_switch()
                return False, err_text

        return False, f"Kill switch is not supported on {sys.platform}."

    def disable_kill_switch(self) -> Tuple[bool, str]:
        """Tear down all kill-switch firewall rules and restore open network access.

        Returns:
            Tuple of (success: bool, status_message: str).
        """
        if not self.requires_admin():
            msg = "Elevation required: Administrator/root privileges needed to disable kill-switch rules."
            logger.warning(msg)
            return False, msg

        if self._is_windows:
            rule_names = [
                f"{RULE_PREFIX}_BlockOutbound",
                f"{RULE_PREFIX}_AllowTunnel",
                f"{RULE_PREFIX}_AllowVPNServers",
                f"{RULE_PREFIX}_AllowDNS",
                f"{RULE_PREFIX}_AllowLocal",
            ]
            for rname in rule_names:
                subprocess.run(
                    ["netsh", "advfirewall", "firewall", "delete", "rule", f"name={rname}"],
                    capture_output=True,
                    check=False,
                )
            self._is_active = False
            msg = "Windows Firewall kill-switch rules removed."
            logger.info(msg)
            return True, msg

        elif self._is_linux:
            # Delete jump in OUTPUT chain
            subprocess.run(["iptables", "-D", "OUTPUT", "-j", "IPCHANGER_KS"], capture_output=True, check=False)
            # Flush and delete chain
            subprocess.run(["iptables", "-F", "IPCHANGER_KS"], capture_output=True, check=False)
            subprocess.run(["iptables", "-X", "IPCHANGER_KS"], capture_output=True, check=False)
            self._is_active = False
            msg = "Linux iptables kill-switch rules removed."
            logger.info(msg)
            return True, msg

        return False, f"Unsupported platform: {sys.platform}"
